function dayOffset(startIso, endIso) {
  return Math.round((Date.parse(`${endIso}T00:00:00`) - Date.parse(`${startIso}T00:00:00`)) / 86400000);
}

export const journeys = JOURNEY_DEFS.map((def) => {
  const legs = def.trainIds.map((id) => byId[id]);
  const first = legs[0];
  const last = legs[legs.length - 1];
  return {
    ...def,
    legs,
    weekday: first.weekday,
    n: first.n,
    departIso: first.departIso,
    arriveIso: last.arriveIso,
    depart: first.depart,
    arrive: last.arrive,
    arriveDaysLater: dayOffset(first.departIso, last.arriveIso),
  };
});

export function trainsTouching(iso) {
  return trains.filter((t) => t.departIso === iso || t.arriveIso === iso);
}
